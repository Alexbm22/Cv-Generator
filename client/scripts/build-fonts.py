"""Builds PDF TTFs, web WOFF2 subsets and @font-face CSS from src/fonts/catalog.json.

Requires: python -m pip install fonttools brotli
"""

import json
import sys
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = ROOT / "src" / "fonts" / "catalog.json"
PDF_DIR = ROOT / "src" / "assets" / "fonts" / "pdf"
WEB_DIR = ROOT / "src" / "assets" / "fonts" / "web"
CSS_PATH = ROOT / "src" / "fonts" / "fonts.generated.css"

STYLE_NAMES = {
    (400, "normal"): "Regular",
    (700, "normal"): "Bold",
    (400, "italic"): "Italic",
    (700, "italic"): "BoldItalic",
}


def parse_ranges(spec):
    codepoints = set()
    for part in spec.split(","):
        value = part.strip()[2:]
        if "-" in value:
            low, high = value.split("-")
            codepoints.update(range(int(low, 16), int(high, 16) + 1))
        else:
            codepoints.add(int(value, 16))
    return codepoints


def instantiate(source, weight):
    variable = TTFont(ROOT / source)
    static = instancer.instantiateVariableFont(
        variable, {"wght": weight, "wdth": 100}, updateFontNames=True
    )
    buffer = BytesIO()
    static.save(buffer)
    return buffer.getvalue()


def subset_font(data, codepoints, flavor=None):
    font = TTFont(BytesIO(data))
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.hinting = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = flavor
    buffer = BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def cmap_of(data):
    return TTFont(BytesIO(data)).getBestCmap()


def main():
    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    scripts = catalog["scripts"]
    required = catalog["required"]

    script_ranges = {name: parse_ranges(spec) for name, spec in scripts.items()}
    pdf_codepoints = set().union(*script_ranges.values())
    for char in required:
        if ord(char) not in pdf_codepoints:
            sys.exit(f"Required character {char!r} is outside every script range")

    PDF_DIR.mkdir(parents=True, exist_ok=True)
    WEB_DIR.mkdir(parents=True, exist_ok=True)
    for old in list(PDF_DIR.glob("*.ttf")) + list(WEB_DIR.glob("*.woff2")):
        old.unlink()

    css_blocks = ["/* Generated by scripts/build-fonts.py from src/fonts/catalog.json. Do not edit. */"]

    for family in catalog["families"]:
        slug = family["name"].replace(" ", "")
        for style, source in family["sources"].items():
            for weight in family["weights"]:
                style_name = STYLE_NAMES[(weight, style)]
                static = instantiate(source, weight)

                pdf_bytes = subset_font(static, pdf_codepoints)
                pdf_cmap = cmap_of(pdf_bytes)
                missing = [c for c in required if ord(c) not in pdf_cmap]
                if missing:
                    sys.exit(f"{slug}-{style_name}.ttf is missing {''.join(missing)}")
                (PDF_DIR / f"{slug}-{style_name}.ttf").write_bytes(pdf_bytes)

                for script, spec in scripts.items():
                    file_name = f"{slug}-{style_name}.{script}.woff2"
                    web_bytes = subset_font(static, script_ranges[script], flavor="woff2")
                    (WEB_DIR / file_name).write_bytes(web_bytes)
                    css_blocks.append(
                        "@font-face {\n"
                        f'  font-family: "{family["name"]}";\n'
                        f"  font-style: {style};\n"
                        f"  font-weight: {weight};\n"
                        "  font-display: swap;\n"
                        f'  src: url("../assets/fonts/web/{file_name}") format("woff2");\n'
                        f"  unicode-range: {spec};\n"
                        "}"
                    )
                print(f"{slug}-{style_name}: pdf {len(pdf_bytes) // 1024} KB")

    CSS_PATH.write_text("\n\n".join(css_blocks) + "\n", encoding="utf-8")
    print(f"Wrote {CSS_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
